/// Словари частотных коротких слов (1–4 буквы) для детектора раскладки.
///
/// Биграммы на 1–3 буквах не дают уверенности («Rfr» = «Как» не проходит
/// порог), поэтому короткие слова решаются по словарям: латинское слово,
/// конверсия которого в ЙЦУКЕН — частотное русское, а само оно — не частотное
/// английское, считается русским в EN-наборе (и симметрично).
///
/// Источник списков — общие знания частотности, сверенные по памяти с
/// частотными словарями: RU — частотный словарь НКРЯ (Ляшевская, Шаров) и
/// OpenSubtitles-ru (служебные слова, местоимения, частицы, разговорные
/// «ща/щас/ок/окей»); EN — Norvig / Google Web Trillion Word Corpus (top
/// слова 1–4 букв) плюс частые IT/чат-сокращения (ok, id, vs, pm, url, api).
///
/// Правила состава (проверяются тестом `ShortWordsTests`):
/// - только нижний регистр, длина 1–4; сравнение — через `contains(_:lang:)`;
/// - **коллизии** (слово одного словаря конвертируется в слово другого:
///   of↔ща, vs↔мы, her↔рук, here↔руку, dj↔во, ofc↔щас) допустимы и намеренны — их решает
///   контекст последнего слова в `Detector`; без контекста — `.unsure`.
///   Слово, чья конверсия — валидное слово другого языка, либо включается в
///   ОБА словаря (коллизия), либо не включается ни в один (herb↔руки,
///   tv↔ем, ev↔ум не включены: русские формы не служебные, а «tv»/«ev» —
///   ходовые сокращения). Осознанная асимметрия в пользу RU: jr↔ок, ye↔ну,
///   tot↔еще — латинская сторона редка, русская частотна, поэтому
///   «jr»/«ye»/«tot» в EN-наборе исправятся в русское;
/// - в словарях нет одиночных латинских букв кроме a/i и одиночных «ж»/«б»
///   (они же `;`/`,`), чтобы точка с запятой/запятая как слово не
