    /// Есть ли слово в словаре языка (без учёта регистра).
    public static func contains(_ word: String, lang: Lang) -> Bool {
        let lowered = word.lowercased()
        return lang == .ru ? ru.contains(lowered) : en.contains(lowered)
    }

